-- Generates LedgerLink/DevAllowlist.lua from the pinned Raid Ledger allowlist,
-- contract/dev-bridge/v1/allowlist.json, so the addon applies exactly that
-- table in game (it cannot read JSON files at runtime).
--   luajit tools/gen_dev_allowlist.lua     rewrite LedgerLink/DevAllowlist.lua
-- spec/dev_probes_spec.lua fails when the committed file differs from what
-- this renders, so re-run it after every tools/sync-contract.sh.
--
-- The rules themselves (grammar, tokenizer, deny-then-allow) are code in
-- DevProbes.lua. They are written against the texts below; a contract change
-- to either one stops this tool until DevProbes.lua is ported to it.
local dkjson = require("dkjson")

local SOURCE = "contract/dev-bridge/v1/allowlist.json"
local TARGET = "LedgerLink/DevAllowlist.lua"
local SEGMENT_PATTERN = "^[A-Za-z_][A-Za-z0-9_]*$" -- the same text is a valid Lua pattern
local TOKENIZER = 'Split the segment at every "_". Inside each piece start a new word before an uppercase letter that'
    .. " follows a lowercase letter or a digit, and before an uppercase letter that is followed by a lowercase letter"
    .. " and preceded by an uppercase letter. Drop empty words. Deny words, deny pairs and deny-exact names compare"
    .. " case-insensitively; allow prefixes and allow-exact names compare case-sensitively."
local KEYS = { "allowlistVersion", "segmentPattern", "maxSegments", "tokenizer", "allowPrefixes", "allowExact",
    "denyWords", "denyWordPairs", "denyExact", "redact", "examples" }

local function list(values)
    local out = {}
    for i, v in ipairs(values) do out[i] = string.format("%q", v) end
    return "{ " .. table.concat(out, ", ") .. " }"
end

local function wrap(prefix, values, indent)
    local lines, line = {}, prefix .. "{"
    for i, v in ipairs(values) do
        local item = string.format(" %q", v) .. (i < #values and "," or "")
        if #line + #item > 112 then
            lines[#lines + 1] = line
            line = indent .. string.sub(item, 2)
        else
            line = line .. item
        end
    end
    lines[#lines + 1] = line .. " },"
    return table.concat(lines, "\n")
end

--- The Lua source for `json` (the allowlist.json text).
local function render(json)
    local a = assert(dkjson.decode(json))
    local known = {}
    for _, k in ipairs(KEYS) do known[k] = true end
    for k in pairs(a) do assert(known[k], "allowlist.json has a new key " .. k .. ": port DevProbes.lua to it") end
    assert(a.segmentPattern == SEGMENT_PATTERN, "allowlist segmentPattern changed: port DevProbes.lua to it")
    assert(a.tokenizer == TOKENIZER, "allowlist tokenizer rule changed: port DevProbes.Words to it")
    assert(type(a.maxSegments) == "number" and type(a.allowlistVersion) == "number")
    local out = {
        "-- GENERATED by tools/gen_dev_allowlist.lua from " .. SOURCE .. " (Raid Ledger",
        "-- dev-bridge v1). Do not edit: re-sync the contract, then re-run the tool.",
        "local _, ns = ...",
        "",
        "ns.DevAllowlist = {",
        string.format("    allowlistVersion = %d,", a.allowlistVersion),
        string.format("    segmentPattern = %q,", a.segmentPattern),
        string.format("    maxSegments = %d,", a.maxSegments),
        wrap("    allowPrefixes = ", a.allowPrefixes, "        "),
        wrap("    allowExact = ", a.allowExact, "        "),
        wrap("    denyWords = ", a.denyWords, "        "),
        "    denyWordPairs = {",
    }
    for _, pair in ipairs(a.denyWordPairs) do out[#out + 1] = "        " .. list(pair) .. "," end
    out[#out + 1] = "    },"
    out[#out + 1] = wrap("    denyExact = ", a.denyExact, "        ")
    out[#out + 1] = "    redact = {"
    for _, r in ipairs(a.redact) do
        local returns = {}
        for i, n in ipairs(r.returns) do returns[i] = string.format("%d", n) end
        out[#out + 1] = string.format("        { fn = %q, returns = { %s }, replacement = %q },", r.fn,
            table.concat(returns, ", "), r.replacement)
    end
    out[#out + 1] = "    },"
    out[#out + 1] = "}"
    return table.concat(out, "\n") .. "\n"
end

local function read(path)
    local f = assert(io.open(path, "rb"))
    local text = f:read("*a")
    f:close()
    return text
end

local M = { SOURCE = SOURCE, TARGET = TARGET, render = render }

--- The rendered source for the pinned allowlist.json.
function M.expected() return render(read(SOURCE)) end

if arg and arg[0] and arg[0]:match("gen_dev_allowlist%.lua$") then
    local f = assert(io.open(TARGET, "wb"))
    f:write(M.expected())
    f:close()
    print("wrote " .. TARGET)
end

return M
